        <p class="eyebrow">HOW IT WORKS</p>
        <h1>From invitation to adventure.</h1>
        <p>
            D&amp;D Portal Dashboard connects organizers and players through
            personal invitations, shared campaigns and practical session tools.
        </p>
    </header>
    <ol class="step-list info-section">
        <li>
            <div>
                <h2>An organizer creates or selects a user</h2>
                <p>
                    The organizer connects the right people to the right
                    campaign and controls who can join.
                </p>
            </div>
        </li>
        <li>
            <div>
                <h2>Receive a personal invitation</h2>
                <p>
                    New users receive a personal registration link or invitation
                    code. Codes are personal and should never be shared.
                </p>
            </div>
        </li>
        <li>
            <div>
                <h2>Create your account or sign in</h2>
                <p>
                    New users register with their personal code. Existing users
                    continue with their existing account and do not need to
                    register again.
                </p>
            </div>
        </li>
        <li>
            <div>
                <h2>Open your dashboard</h2>
                <p>
                    After signing in, you can find the campaigns, players and
                    information connected to your account.
                </p>
            </div>
        </li>
        <li>
            <div>
                <h2>Prepare and participate</h2>
                <p>
                    Answer polls, share availability and view campaigns and
                    upcoming sessions with your party.
                </p>
            </div>
        </li>
        <li>
            <div>
                <h2>Ask your organizer for help</h2>
                <p>
                    If you forget your password, your organizer provides a
                    personal temporary reset link. The public Wiki does not
                    require a dashboard account.
                </p>
            </div>
        </li>
    </ol>
