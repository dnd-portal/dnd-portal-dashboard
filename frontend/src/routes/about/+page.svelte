    <header class="info-page__header">
        <p class="eyebrow">ABOUT D&amp;D PORTAL</p>
        <h1>From scattered plans to shared adventures.</h1>
        <p>
            D&amp;D Portal was created to bring the practical and creative parts
            of tabletop campaigns closer together.
        </p>
    </header>
    <section class="info-section">
        <h2>Why it exists</h2>
        <p>
            Campaigns often depend on a mix of messages, polls, calendars, notes
            and reference pages. Important decisions can disappear in a chat,
            while session planning and campaign information end up spread across
            different places.
        </p>
        <p>
            D&amp;D Portal Dashboard gives players and organizers one shared
            campaign hub for the information that needs to stay connected.
        </p>
    </section>
    <section class="info-section">
        <h2>Dashboard and Wiki</h2>
        <p>
            The Dashboard is for the living campaign: players, sessions,
            planning, decisions and practical details. The <a
                href="https://dnd-portal.com/"
                target="_blank"
                rel="noopener noreferrer">D&amp;D Portal Wiki ↗</a
            > is the public reference space for rules, classes, spells, homebrew
            and other campaign knowledge.
        </p>
    </section>
    <section class="info-section">
        <h2>Still being developed</h2>
        <p>
            D&amp;D Portal is an actively developed independent project. The
            focus remains on making campaigns easier to organize without getting
            in the way of the adventure itself.
        </p>
    </section>
